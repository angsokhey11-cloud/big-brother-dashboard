-- BIG BROTHER Local Brain V3.4: three missing Staff Assistant tables.
-- Target: LOCAL PostgreSQL ONLY, via checksum-verified Code Sync.
-- Schema only. No customer, stock, invoice, cash, or A/R data changes.
-- V3 Telegram bot and cron delivery remain Cloud-only.

DO $guard$
BEGIN
 IF to_regclass('public.staff') IS NULL OR
    to_regclass('public.staff_payment_requests') IS NULL THEN
  RAISE EXCEPTION 'STAFF ASSISTANT SAFE STOP: existing staff/payment request dependencies missing';
 END IF;
 IF to_regclass('public.bb_staff_assistant_accounts') IS NOT NULL OR
    to_regclass('public.bb_staff_assistant_sessions') IS NOT NULL OR
    to_regclass('public.bb_staff_assistant_notification_events') IS NOT NULL THEN
  RAISE EXCEPTION 'STAFF ASSISTANT SAFE STOP: one or more target relations already exist; inspect before installing';
 END IF;
END $guard$;

CREATE TABLE public.bb_staff_assistant_accounts (
 telegram_user_id text PRIMARY KEY
   CONSTRAINT bb_staff_assistant_accounts_telegram_id_check CHECK (telegram_user_id ~ '^[0-9]{5,20}$'),
 staff_id text NOT NULL REFERENCES public.staff(staff_id),
 language text NOT NULL DEFAULT 'km'
   CONSTRAINT bb_staff_assistant_accounts_language_check CHECK (language IN ('km','en')),
 active boolean NOT NULL DEFAULT true,
 verified_by uuid,
 verified_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 language_confirmed boolean NOT NULL DEFAULT false
);
CREATE INDEX bb_staff_assistant_accounts_staff_idx
 ON public.bb_staff_assistant_accounts(staff_id) WHERE active;
ALTER TABLE public.bb_staff_assistant_accounts ENABLE ROW LEVEL SECURITY;
COMMENT ON TABLE public.bb_staff_assistant_accounts IS
 'Admin verified Telegram staff identity and language only. Do not store Telegram messages, snapshots, photos, or search text.';

CREATE TABLE public.bb_staff_assistant_sessions (
 telegram_user_id text PRIMARY KEY REFERENCES public.bb_staff_assistant_accounts(telegram_user_id),
 mode text NOT NULL DEFAULT 'menu',
 customer_id text,
 invoice_id text,
 page integer NOT NULL DEFAULT 0,
 selected_earning_ids jsonb NOT NULL DEFAULT '[]'::jsonb
   CONSTRAINT bb_staff_assistant_sessions_selected_earnings_check CHECK (jsonb_typeof(selected_earning_ids) = 'array'),
 expires_at timestamptz NOT NULL DEFAULT (now() + interval '30 minutes'),
 updated_at timestamptz NOT NULL DEFAULT now(),
 menu_message_id bigint
);
CREATE INDEX bb_staff_assistant_sessions_expiry_idx
 ON public.bb_staff_assistant_sessions(expires_at);
ALTER TABLE public.bb_staff_assistant_sessions ENABLE ROW LEVEL SECURITY;
COMMENT ON TABLE public.bb_staff_assistant_sessions IS
 'Temporary bot routing/IDs only (never message text or images); 30 minute TTL, cleaned by Cloud pg_cron.';

CREATE TABLE public.bb_staff_assistant_notification_events (
 event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id bigint NOT NULL REFERENCES public.staff_payment_requests(request_id),
 event_key text NOT NULL
   CONSTRAINT bb_staff_assistant_notification_events_event_key_check CHECK (event_key IN ('APPROVED','REJECTED','PAID')),
 created_at timestamptz NOT NULL DEFAULT now(),
 processing_at timestamptz,
 attempts integer NOT NULL DEFAULT 0,
 sent_at timestamptz,
 last_error_code text,
 CONSTRAINT bb_staff_assistant_notification_events_request_event_key_key UNIQUE(request_id,event_key)
);
ALTER TABLE public.bb_staff_assistant_notification_events ENABLE ROW LEVEL SECURITY;
COMMENT ON TABLE public.bb_staff_assistant_notification_events IS
 'Temporary request IDs and event state only. No chat text or Telegram snapshots. Event rows auto expire in Cloud.';

-- Verify actual relations and RLS before Code Sync records the migration.
DO $verify$
DECLARE v_missing integer;
BEGIN
 SELECT count(*) INTO v_missing FROM (
  VALUES ('bb_staff_assistant_accounts'),('bb_staff_assistant_sessions'),
         ('bb_staff_assistant_notification_events')
 ) AS names(relname)
 WHERE to_regclass('public.'||relname) IS NULL;
 IF v_missing<>0 THEN
  RAISE EXCEPTION 'STAFF ASSISTANT SAFE STOP: table creation incomplete';
 END IF;
 IF (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
      WHERE n.nspname='public' AND c.relname IN
      ('bb_staff_assistant_accounts','bb_staff_assistant_sessions','bb_staff_assistant_notification_events')
      AND c.relrowsecurity)=3 THEN
  RAISE NOTICE 'STAFF_ASSISTANT_3_TABLES_LOCAL_SCHEMA_READY';
 ELSE
  RAISE EXCEPTION 'STAFF ASSISTANT SAFE STOP: RLS not enabled on all tables';
 END IF;
END $verify$;
